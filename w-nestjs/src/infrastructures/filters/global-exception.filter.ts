import { ExceptionFilter, Catch, ArgumentsHost, HttpException, HttpStatus, Logger } from '@nestjs/common';
import { Request, Response } from 'express';

@Catch()
export class GlobalExceptionFilter implements ExceptionFilter {
	private readonly logger = new Logger(GlobalExceptionFilter.name);

	catch(exception: unknown, host: ArgumentsHost) {
		const ctx = host.switchToHttp();
		const response = ctx.getResponse<Response>();
		const request = ctx.getRequest<Request>();

		let status = HttpStatus.INTERNAL_SERVER_ERROR;
		let title = 'An error occurred while processing your request.';
		let detail: string | undefined = undefined;
		let errors: Record<string, string[]> | undefined = undefined;

		if (exception instanceof HttpException) {
			status = exception.getStatus();
			const resPayload = exception.getResponse();

			if (typeof resPayload === 'object' && resPayload !== null) {
				// NestJS stores the array thrown from exceptionFactory into the 'message' property
				const payloadMessage = (resPayload as any).message;

				if (status === HttpStatus.BAD_REQUEST && Array.isArray(payloadMessage)) {
					title = 'One or more validation errors occurred.';
					// Safely hand over your custom array of objects to the formatter
					errors = this.formatValidationErrors(payloadMessage);
				} else {
					title = (resPayload as any).error ?? this.getStatusTitle(status);
					detail = typeof payloadMessage === 'string' ? payloadMessage : exception.message;
					this.logger.error('Unhandled System Exception:', exception.stack);
				}
			} else if (typeof resPayload === 'string') {
				detail = resPayload;
				title = this.getStatusTitle(status);
			}
		} else if (exception instanceof Error) {
			this.logger.error('Unhandled System Exception:', exception.stack);
			title = 'An internal server error occurred.';

			(request as any).err = exception;
			if ((request as any).raw) {
				(request as any).raw.err = exception;
			}

			// pino-http looks heavily at the response object during res.end()
			(response as any).err = exception;
			if ((response as any).raw) {
				(response as any).raw.err = exception;
			}
		}

		const traceId = request.headers['x-request-id'] ?? `00-${this.generateTraceId()}-00`;

		const problemPayload = {
			type: `https://tools.ietf.org/html/rfc9110#section-15.${this.getRfcSection(status)}`,
			title,
			path: request.path,
			status,
			...(detail && { detail }),
			...(errors && { errors }),
			traceId,
		};

		response
			.status(status)
			.contentType('application/problem+json')
			.json(problemPayload);
	}

	/**
   * Parses the specific array of objects generated by your validation pipe:
   * Input looks like: [ { email: [...] }, { username: [...] } ]
   * Output looks like: { email: [...], username: [...] }
   */
	private formatValidationErrors(messages: unknown[]): Record<string, string[]> {
		const errorMap: Record<string, string[]> = {};

		for (const errorItem of messages ?? []) {
			// Ensure the array element is a valid object containing your property mappings
			if (!errorItem || typeof errorItem !== 'object') {
				continue;
			}

			for (const propertyKey of Object.keys(errorItem)) {
				const constraints = errorItem[propertyKey];
				if (!Array.isArray(constraints)) {
					continue; // Skip if the constraints are not in the expected array format
				}

				errorMap[propertyKey] ??= [];
				errorMap[propertyKey].push(...constraints);
			}
		}

		return errorMap;
	}

	private getStatusTitle(status: number): string {
		switch (status) {
			case 400: return 'Bad Request';
			case 401: return 'Unauthorized';
			case 403: return 'Forbidden';
			case 404: return 'Not Found';
			default: return 'Internal Server Error';
		}
	}

	private getRfcSection(status: number): string {
		switch (status) {
			case 400: return '5.1';
			case 401: return '5.2';
			case 403: return '5.4';
			case 404: return '5.5';
			default: return '6.1';
		}
	}

	private generateTraceId(): string {
		return Math.random().toString(36).substring(2, 15) + Math.random().toString(36).substring(2, 15);
	}
}
